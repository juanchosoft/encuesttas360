-- Llaves primarias y AUTO_INCREMENT en tablas que no los tenían.
-- Si una tabla tiene ids repetidos, ADD PRIMARY KEY falla y la migración se detiene sin cambiar nada más.

SET @pk = (SELECT COUNT(*) FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'tbl_ficha_tecnica_encuestas' AND CONSTRAINT_TYPE = 'PRIMARY KEY');
SET @ddl_pk = IF(@pk = 0, 'ALTER TABLE `tbl_ficha_tecnica_encuestas` ADD PRIMARY KEY (`id`)', 'DO 0');
PREPARE stmt_pk1 FROM @ddl_pk;
EXECUTE stmt_pk1;
DEALLOCATE PREPARE stmt_pk1;
SET @ddl_ai = (SELECT IF(EXTRA LIKE '%auto_increment%', 'DO 0', CONCAT('ALTER TABLE `tbl_ficha_tecnica_encuestas` MODIFY `id` ', COLUMN_TYPE, ' NOT NULL AUTO_INCREMENT COMMENT ', QUOTE(COLUMN_COMMENT)))
  FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'tbl_ficha_tecnica_encuestas' AND COLUMN_NAME = 'id');
PREPARE stmt_ai1 FROM @ddl_ai;
EXECUTE stmt_ai1;
DEALLOCATE PREPARE stmt_ai1;

